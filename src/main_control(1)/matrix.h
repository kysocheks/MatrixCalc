#pragma once

// основные структуры матрицы
// ненулевой элемент матрицы
struct Node
{
    int row;    // номер строки
    double value;// значение элемента
    Node* next; // указатель на след. ненулевой элемент столбца
};

// ненулевой столбец
struct Colhead
{
    int col;        // номер столбца
    Node* first_el; // указатель на первый ненулевой эл. столбца
    Colhead* next;  // указатель на следующий ненулевой столбец
};

// матрица
struct Matrix
{
    int rows;               // кол-во строк
    int cols;               // кол-во столбцов
    long long nonZeroCount; // кол-во ненулевых эл. матрицы
    Colhead* first_col;     // указатель на первый ненулевой столбец матрицы
};

// временное представление матрицы
struct Entry
{
    int row;     // строка
    int col;     // столбец
    double value;//значение
};
